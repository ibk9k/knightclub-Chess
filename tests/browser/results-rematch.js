// Run locally with playwright-cli run-code --filename=tests/browser/results-rematch.js.
async (page) => {
  const results = [];
  const assert = (condition, message) => { if (!condition) throw new Error(message); results.push(message); };
  const browser = page.context().browser();
  const hostContext = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const guest = await context.newPage(), origin = new URL(page.url()).origin;
  page = await hostContext.newPage();
  const play = async (actor, from, to) => {
    await actor.getByRole('button', { name: new RegExp(`^${from} (white|black) `) }).click();
    await actor.getByRole('button', { name: new RegExp(`^${to}( (white|black) \\w+)? legal destination$`) }).click();
  };
  const resign = async (actor) => {
    await actor.getByRole('button', { name: 'Resign game', exact: true }).click();
    await actor.locator('.app-dialog').getByRole('button', { name: 'Resign game', exact: true }).click();
  };
  try {
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.goto(origin);
    await page.getByRole('button', { name: 'Play online', exact: true }).click();
    await page.getByRole('textbox', { name: /Your name/ }).fill('Alice');
    await page.getByRole('combobox', { name: 'Online color' }).selectOption('w');
    await page.getByRole('button', { name: 'Create private room', exact: true }).click();
    await page.locator('.online-room-status.waiting').waitFor();
    const code = (await page.locator('.room-code-box strong').textContent()).trim();
    await guest.goto(`${origin}/?join=${code}`);
    await guest.getByRole('textbox', { name: /Your name/ }).fill('Bob');
    await guest.getByRole('button', { name: 'Join', exact: true }).click();
    await page.locator('.online-room-status.active').waitFor();
    await play(page, 'f2', 'f3');
    await guest.getByRole('button', { name: 'f3 white pawn', exact: true }).waitFor();
    await play(guest, 'e7', 'e5');
    await page.getByRole('button', { name: 'e5 black pawn', exact: true }).waitFor();
    await play(page, 'g2', 'g4');
    await guest.getByRole('button', { name: 'g4 white pawn', exact: true }).waitFor();
    await play(guest, 'd8', 'h4');
    await guest.getByRole('heading', { name: 'You won!', exact: true }).waitFor();
    assert(await guest.locator('.board-confetti i').count() === 64, 'A winner gets board-confined confetti');
    assert(await guest.locator('.board-confetti').evaluate(el => getComputedStyle(el).pointerEvents) === 'none', 'Confetti does not block the board or controls');
    await guest.screenshot({ path: 'output/playwright/win-confetti.png', fullPage: true });
    await page.getByRole('heading', { name: 'You lost this one.', exact: true }).waitFor();
    assert(await page.locator('.fallen-king').evaluate(el => getComputedStyle(el).animationName) === 'king-concedes', 'A loss tips the king instead of showing confetti');
    assert(await page.locator('.board-confetti').count() === 0, 'The losing player does not receive win confetti');
    await page.screenshot({ path: 'output/playwright/loss-king.png', fullPage: true });
    await page.getByRole('button', { name: 'Play again', exact: true }).click();
    await page.getByRole('button', { name: 'Rematch requested', exact: true }).waitFor();
    assert(await page.locator('.online-room-status.finished').count() === 1, 'Play again waits for the same opponent to agree');
    await guest.getByRole('button', { name: 'Accept rematch', exact: true }).waitFor();
    await guest.getByRole('button', { name: 'Decline', exact: true }).click();
    await page.getByRole('button', { name: 'Play again', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Play again', exact: true }).click();
    await guest.getByRole('button', { name: 'Accept rematch', exact: true }).waitFor();
    await guest.getByRole('button', { name: 'Accept rematch', exact: true }).click();
    await page.locator('.online-room-status.active').waitFor();
    await guest.locator('.online-room-status.active').waitFor();
    assert(await page.locator('.room-code-box strong').textContent() === code, 'A rematch keeps the same private room');
    assert(await page.locator('.online-seats strong').textContent() === 'You play black' && await guest.locator('.online-seats strong').textContent() === 'You play white', 'Both original players stay and colors switch');
    assert(await page.locator('.move-cell').count() === 0 && await page.locator('.game-result').count() === 0, 'The rematch resets moves, result, and animations');
    assert(await guest.evaluate(code => sessionStorage.getItem(`knight-club-celebrated:${code}:2`) === null, code), 'The previous win cannot consume the next round’s celebration');
    await play(guest, 'e2', 'e4');
    await page.getByRole('button', { name: 'e4 white pawn', exact: true }).waitFor();
    await play(page, 'e7', 'e5');
    await guest.getByRole('button', { name: 'e5 black pawn', exact: true }).waitFor();
    await guest.emulateMedia({ reducedMotion: 'reduce' });
    await resign(page);
    await guest.getByRole('heading', { name: 'You won!', exact: true }).waitFor();
    assert(await guest.locator('.board-confetti').count() === 0, 'Reduced-motion players receive a static win result');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.waitForFunction(() => new DOMMatrixReadOnly(getComputedStyle(document.querySelector('.sidebar')).transform).m41 <= -213);
    await page.getByRole('region', { name: 'Game result' }).scrollIntoViewIfNeeded();
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'The result and rematch controls fit on a phone');
    await page.screenshot({ path: 'output/playwright/result-mobile.png', fullPage: false });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.getByRole('button', { name: 'Review game', exact: true }).click();
    await guest.getByRole('button', { name: 'Play again', exact: true }).click();
    await page.getByRole('button', { name: 'Accept rematch', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Accept rematch', exact: true }).click();
    await guest.locator('.online-room-status.active').waitFor();
    assert(await page.getByRole('tab', { name: 'Analysis FREE' }).isDisabled(), 'Rematches still arrive during post-game review, then pause analysis');
    await resign(page);
    await page.getByRole('button', { name: 'Leave room', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Leave room', exact: true }).click();
    await page.getByRole('button', { name: 'Play chess', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('.engine-status.ready'));
    await page.getByRole('button', { name: 'Nova, 400, Beginner', exact: true }).click();
    await page.getByRole('button', { name: 'New game', exact: false }).click();
    await play(page, 'e2', 'e4');
    await page.waitForFunction(() => document.querySelector('.game-status')?.textContent?.includes('Your move'));
    await page.getByRole('button', { name: 'Atlas, 1600, Advanced', exact: true }).click();
    await resign(page);
    await page.getByRole('button', { name: 'Play again', exact: true }).click();
    assert((await page.locator('.player-name').first().textContent()).includes('Nova'), 'Bot Play again retains the actual opponent even if another bot was selected');
    assert(await page.getByRole('combobox', { name: 'Time control', exact: true }).inputValue() === '0', 'Bot rematches retain the same time control');
    assert(await page.locator('.game-result').count() === 0, 'A fresh bot game clears the old result');
    return results;
  } finally { await context.close(); await hostContext.close(); }
}
