// Run through playwright-cli run-code --filename=tests/browser/multiplayer.js.
async (page) => {
  const results = [];
  const assert = (condition, message) => { if (!condition) throw new Error(message); results.push(message); };
  const browser = page.context().browser();
  const secondContext = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const thirdContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const guest = await secondContext.newPage(), stranger = await thirdContext.newPage();
  const origin = new URL(page.url()).origin;
  const play = async (actor, from, to) => {
    await actor.getByRole('button', { name: new RegExp(`^${from} (white|black) `) }).click();
    await actor.getByRole('button', { name: new RegExp(`^${to}( (white|black) \\w+)? legal destination$`) }).click();
  };
  try {
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.goto(origin);
    await page.getByRole('combobox', { name: 'Time control', exact: true }).waitFor();
    assert(await page.getByRole('combobox', { name: 'Time control', exact: true }).inputValue() === '0', 'Bot games default to no clock');
    await page.getByRole('button', { name: 'Play online', exact: true }).click();
    await page.getByRole('textbox', { name: /Your name/ }).fill('Alice');
    await page.getByRole('combobox', { name: 'Online color' }).selectOption('w');
    await page.getByRole('button', { name: 'Create private room', exact: true }).click();
    await page.locator('.online-room-status.waiting').waitFor();
    const code = (await page.locator('.room-code-box strong').textContent()).trim();
    const invite = await page.getByRole('textbox', { name: 'Invite link', exact: true }).inputValue();
    assert(invite === `${origin}/?join=${code}`, 'Private rooms provide a working invite link and code');
    await page.screenshot({ path: 'output/playwright/private-room-desktop.png', fullPage: true });
    await guest.goto(invite);
    await guest.getByRole('textbox', { name: /Your name/ }).fill('Bob');
    assert(await guest.getByRole('textbox', { name: 'Have an invite?' }).inputValue() === code, 'Invite links prefill the room code');
    await guest.getByRole('button', { name: 'Join', exact: true }).click();
    await guest.locator('.online-room-status.active').waitFor();
    await page.locator('.online-room-status.active').waitFor();
    assert(await guest.locator('.online-seats strong').textContent() === 'You play black', 'The invited player receives the opposite color');
    assert(await page.getByRole('button', { name: 'Hint', exact: true }).isDisabled(), 'Hints are disabled during online play');
    assert(await page.getByRole('tab', { name: 'Analysis FREE' }).isDisabled(), 'Live engine analysis is disabled during online play');
    assert(await page.locator('.evaluation-bar').count() === 0, 'The evaluation bar is hidden during online play');
    await stranger.goto(invite);
    await stranger.getByRole('button', { name: 'Join', exact: true }).click();
    await stranger.getByRole('alert').filter({ hasText: 'already has two players' }).waitFor();
    assert(true, 'A third visitor cannot take a seat in a full private game');
    assert(await stranger.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Invite lobby fits a phone without horizontal overflow');
    await stranger.screenshot({ path: 'output/playwright/private-room-mobile.png', fullPage: true });
    await thirdContext.close();
    await play(page, 'e2', 'e4');
    await guest.getByRole('button', { name: 'e4 white pawn', exact: true }).waitFor();
    await play(guest, 'd7', 'd5');
    await page.getByRole('button', { name: 'd5 black pawn', exact: true }).waitFor();
    await play(page, 'e4', 'd5');
    await guest.getByRole('button', { name: 'd5 white pawn', exact: true }).waitFor();
    assert(await page.getByLabel('White is ahead by 1 point of material', { exact: true }).textContent() === '+1', 'A pawn capture shows +1 beside the captured pieces');
    assert(await guest.getByLabel('White is ahead by 1 point of material', { exact: true }).textContent() === '+1', 'Material advantage synchronizes to the other player');
    await play(guest, 'd8', 'd5');
    await page.getByRole('button', { name: 'd5 black queen', exact: true }).waitFor();
    assert(await page.locator('.material-advantage').count() === 0, 'Equal material after a trade clears the advantage');
    await page.reload();
    await page.locator('.online-room-status.active').waitFor();
    assert(await page.getByRole('button', { name: 'd5 black queen', exact: true }).count() === 1, 'Refreshing restores the same seat and full game position');
    await page.context().setOffline(true);
    await page.getByText('Connection lost. Reconnecting…', { exact: true }).waitFor();
    await page.context().setOffline(false);
    await page.getByText('Connection lost. Reconnecting…', { exact: true }).waitFor({ state: 'hidden' });
    assert(true, 'A dropped connection recovers without losing the game');
    await page.getByRole('button', { name: 'Offer a draw', exact: true }).click();
    await guest.getByRole('button', { name: 'Accept draw', exact: true }).waitFor();
    await guest.getByRole('button', { name: 'Accept draw', exact: true }).click();
    await page.locator('.online-result').filter({ hasText: 'Draw by agreement' }).waitFor();
    assert(await page.getByRole('tab', { name: 'Analysis FREE' }).isEnabled(), 'Analysis unlocks after the shared game ends');
    assert(await page.evaluate(() => JSON.parse(localStorage.getItem('knight-club-games') || '[]').some(game => game.result === 'Draw by agreement')), 'Completed online games are saved for review');
    await page.screenshot({ path: 'output/playwright/online-game-desktop.png', fullPage: true });
    await page.getByRole('button', { name: 'Play another online game', exact: true }).click();
    await guest.getByRole('button', { name: 'Play another online game', exact: true }).click();
    await page.getByRole('button', { name: 'Find a random opponent', exact: true }).click();
    await page.locator('.online-room-status.waiting').waitFor();
    assert(await page.getByRole('textbox', { name: 'Invite link', exact: true }).isVisible(), 'Random matchmaking also offers an invite link while waiting');
    await guest.getByRole('button', { name: 'Find a random opponent', exact: true }).click();
    await guest.locator('.online-room-status.active').waitFor();
    await page.locator('.online-room-status.active').waitFor();
    assert(await page.locator('.room-code-box strong').textContent() === await guest.locator('.room-code-box strong').textContent(), 'Two random searches meet in the same room');
    await guest.getByRole('button', { name: 'Leave game', exact: true }).click();
    await guest.getByRole('button', { name: 'Resign game', exact: true }).last().click();
    await page.locator('.online-result').filter({ hasText: 'wins by resignation' }).waitFor();
    assert(true, 'Leaving an active room awards the result to the opponent');
    await page.getByRole('button', { name: 'Play another online game', exact: true }).click();
    await page.getByRole('button', { name: 'Create private room', exact: true }).click();
    await page.locator('.online-room-status.waiting').waitFor();
    await page.getByRole('button', { name: 'Cancel room', exact: true }).click();
    await page.getByRole('button', { name: 'Create private room', exact: true }).waitFor();
    assert(await page.locator('.online-room-status').count() === 0, 'Cancelling a waiting room returns to the online lobby');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.waitForFunction(() => new DOMMatrixReadOnly(getComputedStyle(document.querySelector('.sidebar')).transform).m41 <= -213);
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'The online lobby and board fit a phone');
    await page.screenshot({ path: 'output/playwright/online-lobby-mobile.png', fullPage: true });
    return results;
  } finally {
    await secondContext.close();
    if (thirdContext.pages().length) await thirdContext.close();
    await page.context().setOffline(false);
  }
}
