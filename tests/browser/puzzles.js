async (basePage) => {
  const origin = new URL(basePage.url()).origin;
  const browser = basePage.context().browser();
  const desktop = await browser.newContext({ viewport: { width: 1440, height: 1080 }, timezoneId: 'Asia/Karachi' });
  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, timezoneId: 'Asia/Karachi', reducedMotion: 'reduce' });
  const page = await desktop.newPage(), phone = await mobile.newPage();
  const crashes = []; page.on('pageerror', error => crashes.push(error.message)); phone.on('pageerror', error => crashes.push(error.message));
  const check = (value, message) => { if (!value) throw new Error(message); };
  const board = target => target.getByRole('group', { name: 'Puzzle chessboard', exact: true });
  const square = (target, name) => board(target).locator(`[data-square="${name}"]`);
  const move = async (target, text, touch = false) => {
    const click = async locator => touch ? locator.tap() : locator.click();
    await click(square(target, text.slice(0, 2))); await click(square(target, text.slice(2, 4)));
    if (text[4]) await click(target.getByRole('button', { name: `Promote to ${{ q: 'queen', r: 'rook', b: 'bishop', n: 'knight' }[text[4]]}`, exact: true }));
    await square(target, text.slice(0, 2)).locator('img.piece').waitFor({ state: 'hidden' });
    await target.waitForFunction(() => document.querySelector('.puzzle-feedback.is-success') || document.querySelector('.puzzle-feedback')?.textContent.includes('Good move. Keep going!'));
  };
  const assertNoOverflow = async target => check(await target.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Puzzle layout overflows horizontally');
  try {
    await page.clock.install({ time: new Date('2026-10-23T07:00:00Z') });
    await page.goto(`${origin}/?view=puzzles`, { waitUntil: 'domcontentloaded' });
    await board(page).waitFor();
    check(await page.locator('.puzzle-catalogue-row').count() === 12, 'Catalogue must be paginated');
    await assertNoOverflow(page);
    await page.screenshot({ path: 'output/playwright/puzzles-desktop.png' });
    const dailyId = await page.locator('.puzzle-source').innerText();
    await page.getByRole('button', { name: 'View solution', exact: true }).click();
    await page.getByRole('button', { name: 'Next solution move', exact: true }).click();
    check((await page.locator('.puzzle-solution-controls').innerText()).includes('1 /'), 'Solution review must step the board');
    check((await page.locator('.puzzle-streak strong').innerText()).startsWith('0'), 'Revealing a solution cannot grant a streak');
    check((await page.locator('.puzzle-catalogue-heading > span').innerText()).startsWith('0 /'), 'Revealing a solution cannot mark it solved');
    await page.getByRole('button', { name: 'Try again', exact: true }).click();
    for (let step = 0; step < 4; step++) {
      await page.getByRole('button', { name: /^Give me a hint/ }).click();
      await page.getByRole('button', { name: /^A little more help/ }).click();
      await page.getByRole('button', { name: /^A little more help/ }).click();
      const hint = await page.locator('.puzzle-hint p').innerText();
      const match = /([a-h][1-8]) → ([a-h][1-8])/.exec(hint); check(!!match, 'Final hint must explain a playable move');
      const promotion = /promoting to a (queen|rook|bishop|knight)/.exec(hint);
      await move(page, match[1] + match[2] + (promotion ? { queen: 'q', rook: 'r', bishop: 'b', knight: 'n' }[promotion[1]] : ''));
      if (await page.locator('.puzzle-feedback.is-success').count()) break;
    }
    await page.getByRole('heading', { name: 'You found it.', exact: true }).waitFor();
    check((await page.locator('.puzzle-streak strong').innerText()).startsWith('1'), 'Solving daily with hints should create a streak');
    check((await page.locator('.puzzle-catalogue-heading > span').innerText()).startsWith('1 /'), 'Solved catalogue count must be unique');
    await page.reload({ waitUntil: 'domcontentloaded' }); await board(page).waitFor();
    check((await page.locator('.puzzle-streak strong').innerText()).startsWith('1'), 'Streak must survive reload');
    await page.clock.setSystemTime(new Date('2026-10-23T19:00:01Z'));
    await page.evaluate(() => window.dispatchEvent(new Event('focus')));
    await page.getByRole('button', { name: 'Play daily', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Play daily', exact: true }).click();
    check((await page.locator('.puzzle-source').innerText()) !== dailyId, 'The next day must offer a different daily puzzle');
    check((await page.locator('.puzzle-streak strong').innerText()).startsWith('1'), 'Yesterday’s streak stays active until today is missed');
    await page.getByLabel('Theme', { exact: true }).selectOption('pin');
    await page.getByLabel('Difficulty', { exact: true }).selectOption('Easy');
    check(await page.locator('.puzzle-catalogue-row').count() > 0, 'Theme and level filters must return puzzles');
    await page.getByRole('textbox', { name: 'Search challenges', exact: true }).fill('not-a-chess-theme');
    await page.locator('.puzzle-empty').waitFor();
    await page.getByRole('button', { name: 'Clear filters', exact: true }).click();
    await page.getByLabel('Progress', { exact: true }).selectOption('solved');
    check(await page.locator('.puzzle-catalogue-row').count() === 1, 'Solved filter should use stored progress');
    await page.getByRole('button', { name: 'Clear filters', exact: true }).click();
    const first = await page.locator('.puzzle-catalogue-row').first().getAttribute('aria-label');
    await page.getByRole('button', { name: 'Next', exact: true }).click();
    check(await page.locator('.puzzle-catalogue-row').first().getAttribute('aria-label') !== first, 'Pagination must display different challenges');
    await page.getByRole('button', { name: 'Previous', exact: true }).click();
    await page.getByRole('button', { name: 'Play Challenge 001, Mate in one, Easy', exact: true }).click();
    await square(page, 'd6').focus(); await page.keyboard.press('ArrowRight');
    check(await page.evaluate(() => document.activeElement?.getAttribute('data-square')) === 'c6', 'Arrow keys must navigate the puzzle board');
    await page.keyboard.press('Space'); await page.keyboard.press('Escape');
    check(await board(page).locator('[aria-pressed="true"]').count() === 0, 'Escape must clear keyboard selection');
    await square(page, 'd6').click(); await square(page, 'e5').click();
    await page.locator('.puzzle-feedback.is-error').waitFor();
    check((await page.locator('.puzzle-feedback').innerText()).includes('stronger continuation'), 'Wrong legal moves should give feedback');
    check((await square(page, 'd6').getAttribute('aria-label')).includes('black queen'), 'A wrong move must leave the position unchanged');
    await page.evaluate(() => { window.puzzleNativeDrags = 0; document.addEventListener('dragstart', () => window.puzzleNativeDrags++); });
    const from = await square(page, 'd6').boundingBox(), to = await square(page, 'h2').boundingBox();
    await page.mouse.move(from.x + from.width / 2, from.y + from.height / 2); await page.mouse.down();
    await page.mouse.move(to.x + to.width / 2, to.y + to.height / 2, { steps: 10 });
    check(await page.locator('.drag-piece').count() === 1, 'Puzzle drag must use the custom piece preview');
    await page.mouse.up();
    await page.getByRole('heading', { name: 'You found it.', exact: true }).waitFor();
    check(await page.evaluate(() => window.puzzleNativeDrags) === 0, 'Puzzle drag must not use browser copy/drag behavior');
    await phone.goto(`${origin}/?puzzle=00L4x`, { waitUntil: 'domcontentloaded' });
    await board(phone).waitFor(); await assertNoOverflow(phone);
    await phone.screenshot({ path: 'output/playwright/puzzles-mobile.png' });
    await phone.getByRole('button', { name: 'Hint', exact: true }).tap();
    const mobileHint = await phone.locator('.puzzle-hint').boundingBox();
    check(mobileHint && mobileHint.y >= 0 && mobileHint.y + mobileHint.height <= 844, 'The phone hint shortcut must bring its explanation into view');
    await move(phone, 'e7e8q', true);
    await move(phone, 'e1e8', true);
    await phone.getByRole('heading', { name: 'You found it.', exact: true }).waitFor();
    check(await phone.locator('.board-confetti').count() === 0, 'Reduced-motion users should not get confetti');
    await phone.getByRole('button', { name: 'Next challenge', exact: true }).tap();
    await board(phone).waitFor();
    await phone.getByRole('button', { name: 'Open navigation', exact: true }).tap();
    await phone.getByRole('button', { name: 'Play chess', exact: true }).tap();
    await phone.getByRole('group', { name: 'Chessboard', exact: true }).waitFor();
    check((await phone.getByRole('button', { name: 'e2 white pawn', exact: true }).count()) === 1, 'Returning to normal play should retain a normal game');
    check(crashes.length === 0, `Browser errors: ${crashes.join('; ')}`);
    return { catalogue: 382, hintsAndDaily: true, solutionReview: true, savedProgress: true, midnightRollover: true, filtersAndPagination: true, customDrag: true, mobilePromotion: true, reducedMotion: true, normalPlay: true, browserErrors: crashes };
  } catch (error) {
    await page.screenshot({ path: 'output/playwright/puzzles-failure.png' }).catch(() => {});
    throw new Error(`${error.message}\nPuzzle panel: ${await page.locator('.puzzle-companion').innerText().catch(() => 'unavailable')}`);
  } finally { await desktop.close(); await mobile.close(); }
}
